__MODULES["Util"] = function()
	--[[ Util.lua — small helpers shared by client and server. ]]

	local Util = {}

	local SUFFIXES = {
		"", "K", "M", "B", "T", "Qa", "Qi", "Sx", "Sp", "Oc", "No",
		"Dc", "UDc", "DDc", "TDc", "QaDc", "QiDc", "SxDc", "SpDc", "OcDc", "NoDc", "Vg",
	}

	--- 1234567 -> "1.23M"
	function Util.abbreviate(n: number): string
		if n ~= n then return "0" end            -- NaN guard
		local sign = n < 0 and "-" or ""
		n = math.abs(n)
		if n < 1000 then
			return sign .. tostring(math.floor(n + 0.5))
		end
		local index = math.floor(math.log(n, 1000))
		index = math.clamp(index, 1, #SUFFIXES - 1)
		local scaled = n / (1000 ^ index)
		local text
		if scaled >= 100 then
			text = string.format("%.0f", scaled)
		elseif scaled >= 10 then
			text = string.format("%.1f", scaled)
		else
			text = string.format("%.2f", scaled)
		end
		-- Trim trailing zeros, but ONLY past a decimal point. Trimming
		-- unconditionally turns "320" into "32", i.e. 320K displays as 32K.
		if text:find("%.") then
			text = text:gsub("0+$", "")
			text = text:gsub("%.$", "")
		end
		return sign .. text .. SUFFIXES[index + 1]
	end

	--- 1234567 -> "1,234,567"
	function Util.comma(n: number): string
		local whole = string.format("%.0f", math.abs(n))
		local out = whole:reverse():gsub("(%d%d%d)", "%1,"):reverse()
		out = out:gsub("^,", "")
		return (n < 0 and "-" or "") .. out
	end

	function Util.weld(a: BasePart, b: BasePart, name: string?): WeldConstraint
		local weld = Instance.new("WeldConstraint")
		weld.Name = name or "TungWeld"
		weld.Part0 = a
		weld.Part1 = b
		weld.Parent = a
		return weld
	end

	--- Welds every descendant BasePart of `model` to `root` and anchors nothing.
	function Util.weldModel(model: Model, root: BasePart)
		for _, part in ipairs(model:GetDescendants()) do
			if part:IsA("BasePart") and part ~= root then
				part.Anchored = false
				Util.weld(root, part)
			end
		end
	end

	function Util.setCollision(model: Instance, group: string)
		for _, part in ipairs(model:GetDescendants()) do
			if part:IsA("BasePart") then
				part.CollisionGroup = group
			end
		end
		if model:IsA("BasePart") then
			model.CollisionGroup = group
		end
	end

	function Util.newPart(props: { [string]: any }): Part
		local part = Instance.new("Part")
		part.Anchored = true
		part.CanCollide = false
		part.CastShadow = false
		part.TopSurface = Enum.SurfaceType.Smooth
		part.BottomSurface = Enum.SurfaceType.Smooth
		for key, value in pairs(props) do
			if key ~= "Parent" then
				(part :: any)[key] = value
			end
		end
		if props.Parent then
			part.Parent = props.Parent
		end
		return part
	end

	function Util.roundedFrame(parent: Instance, radius: number): UICorner
		local corner = Instance.new("UICorner")
		corner.CornerRadius = UDim.new(0, radius)
		corner.Parent = parent
		return corner
	end

	function Util.shallowCopy(t)
		local out = {}
		for k, v in pairs(t) do
			out[k] = v
		end
		return out
	end

	function Util.count(t): number
		local n = 0
		for _ in pairs(t) do
			n += 1
		end
		return n
	end

	--- Deterministic-ish pseudo random from a string seed (used for plot flavour).
	function Util.hash(s: string): number
		local h = 5381
		for i = 1, #s do
			h = (h * 33 + s:byte(i)) % 2147483647
		end
		return h
	end

	function Util.lerpColor(a: Color3, b: Color3, t: number): Color3
		return a:Lerp(b, math.clamp(t, 0, 1))
	end

	--- Safely reads a character's humanoid + root, or nil.
	function Util.getRig(model: Instance?): (Humanoid?, BasePart?)
		if not model or not model:IsA("Model") then
			return nil, nil
		end
		local humanoid = model:FindFirstChildOfClass("Humanoid")
		local root = model:FindFirstChild("HumanoidRootPart")
		if humanoid and root and root:IsA("BasePart") then
			return humanoid, root
		end
		return nil, nil
	end

	return Util
end


__MODULES["CombatService"] = function()
	--[[
		CombatService.lua — bats, swinging, damage, knockback and PvP rules.

		Design notes
		  * The server is authoritative. Tool.Activated replicates, so the client
		    never gets to say "I hit them"; it only asks for a swing.
		  * PvP is opt-in by geography: you can only hurt another player while
		    BOTH of you are inside the arena ring. Your plot is a safe zone.
		  * Sahur raiders can be hit anywhere.
	]]

	local Req = __Req
	local Config = Req("Config")
	local Util = Req("Util")
	local Fx = Req("Fx")
	local Net = Req("Net")
	local TungModels = Req("TungModels")
	local DataService = Req("DataService")
	local Economy = Req("Economy")

	local Players = game:GetService("Players")
	local TweenService = game:GetService("TweenService")
	local Debris = game:GetService("Debris")

	local CombatService = {}

	local hitFeedback = Net.event("HitFeedback")
	local knockbackRemote = Net.event("Knockback")

	local state: { [Player]: { lastSwing: number, combo: number, comboAt: number } } = {}

	local function stateFor(player: Player)
		local s = state[player]
		if not s then
			s = { lastSwing = 0, combo = 0, comboAt = 0 }
			state[player] = s
		end
		return s
	end

	-- ─────────────────────────────────────────────────────────────────────────────
	-- zones
	-- ─────────────────────────────────────────────────────────────────────────────

	function CombatService.inArena(position: Vector3): boolean
		local flat = Vector3.new(position.X, 0, position.Z)
		return flat.Magnitude <= Config.World.ArenaRadius
	end

	--- Can `attacker` (a Player) hurt `victimModel`?
	function CombatService.canDamage(attacker: Player, victimModel: Model): boolean
		if victimModel:GetAttribute("IsSahurNPC") then
			return true
		end
		local victimPlayer = Players:GetPlayerFromCharacter(victimModel)
		if not victimPlayer then
			return false
		end
		if victimPlayer == attacker then
			return false
		end
		if not Config.Combat.ArenaPvP then
			return true
		end
		local attackerChar = attacker.Character
		if not attackerChar then
			return false
		end
		return CombatService.inArena(attackerChar:GetPivot().Position)
			and CombatService.inArena(victimModel:GetPivot().Position)
	end

	-- ─────────────────────────────────────────────────────────────────────────────
	-- bats
	-- ─────────────────────────────────────────────────────────────────────────────

	local function removeBats(container: Instance?)
		if not container then
			return
		end
		for _, child in ipairs(container:GetChildren()) do
			if child:IsA("Tool") and child:GetAttribute("BatId") then
				child:Destroy()
			end
		end
	end

	function CombatService.equipCurrentBat(player: Player)
		-- a character can spawn before the DataStore read finishes on first join
		local profile = DataService.get(player)
		local deadline = os.clock() + 12
		while not profile and player.Parent and os.clock() < deadline do
			task.wait(0.25)
			profile = DataService.get(player)
		end
		if not profile or not player.Parent then
			return
		end
		local tier = math.clamp(profile.batTier or 1, 1, #Config.Bats)
		local def = Config.Bats[tier]

		removeBats(player:FindFirstChildOfClass("Backpack"))
		removeBats(player.Character)

		local tool = TungModels.buildBatTool(def)
		tool.Parent = player:FindFirstChildOfClass("Backpack")

		CombatService.bind(player, tool)
	end

	function CombatService.grantBat(player: Player, batId: string)
		local def = Config.BatById[batId]
		local profile = DataService.get(player)
		if not def or not profile then
			return
		end
		if def.tier <= (profile.batTier or 1) then
			return
		end
		profile.batTier = def.tier
		CombatService.equipCurrentBat(player)
		Economy.push(player)
		Economy.notify(player, {
			kind = "gear",
			title = "NEW BAT: " .. def.name,
			body = ("%d damage  •  %.0f%% crit"):format(def.damage, def.crit * 100),
		})
	end

	-- ─────────────────────────────────────────────────────────────────────────────
	-- swinging
	-- ─────────────────────────────────────────────────────────────────────────────

	local function animateSwing(character: Model, duration: number)
		local arm = character:FindFirstChild("Right Arm") or character:FindFirstChild("RightHand")
		local grip = arm and arm:FindFirstChild("RightGrip")
		if not grip or not grip:IsA("Weld") then
			return
		end
		local base = grip:GetAttribute("BaseC0")
		if not base then
			grip:SetAttribute("BaseC0", grip.C0)
			base = grip.C0
		end

		local windUp = TweenService:Create(grip, TweenInfo.new(duration * 0.25, Enum.EasingStyle.Back, Enum.EasingDirection.Out), {
			C0 = base * CFrame.Angles(math.rad(70), 0, math.rad(-25)),
		})
		local strike = TweenService:Create(grip, TweenInfo.new(duration * 0.3, Enum.EasingStyle.Quart, Enum.EasingDirection.Out), {
			C0 = base * CFrame.Angles(math.rad(-95), 0, math.rad(35)),
		})
		local reset = TweenService:Create(grip, TweenInfo.new(duration * 0.45, Enum.EasingStyle.Quad, Enum.EasingDirection.Out), {
			C0 = base,
		})

		windUp:Play()
		windUp.Completed:Once(function()
			strike:Play()
			strike.Completed:Once(function()
				reset:Play()
			end)
		end)
	end

	--- Applies damage to any humanoid, from a player or from an NPC.
	function CombatService.damage(victimModel: Model, amount: number, sourcePosition: Vector3?, knockback: number?, attacker: Player?)
		local humanoid, root = Util.getRig(victimModel)
		if not humanoid or not root or humanoid.Health <= 0 then
			return false
		end

		-- classic "creator" tag so whoever landed the last hit gets the credit
		if attacker then
			local old = humanoid:FindFirstChild("creator")
			if old then
				old:Destroy()
			end
			local tag = Instance.new("ObjectValue")
			tag.Name = "creator"
			tag.Value = attacker
			tag.Parent = humanoid
			Debris:AddItem(tag, 8)
		end

		humanoid:TakeDamage(amount)

		if knockback and knockback > 0 and sourcePosition then
			local direction = (root.Position - sourcePosition)
			direction = Vector3.new(direction.X, 0, direction.Z)
			if direction.Magnitude < 0.1 then
				direction = Vector3.new(0, 0, 1)
			end
			direction = direction.Unit
			local impulse = (direction * knockback + Vector3.new(0, knockback * 0.45, 0)) * root.AssemblyMass * 0.6

			local victimPlayer = Players:GetPlayerFromCharacter(victimModel)
			if victimPlayer then
				-- The victim's own client owns their character's physics, so a
				-- server-side ApplyImpulse is overwritten on the next replication
				-- tick. Ask the owning client to apply it instead.
				knockbackRemote:FireClient(victimPlayer, impulse)
			else
				root:ApplyImpulse(impulse)
			end
		end

		if attacker then
			hitFeedback:FireClient(attacker, {
				damage = amount,
				position = root.Position,
				killed = humanoid.Health <= 0,
			})
		end
		return true
	end

	local function hitscan(character: Model, reach: number): { Model }
		local root = character:FindFirstChild("HumanoidRootPart") :: BasePart
		if not root then
			return {}
		end
		local size = Config.Combat.HitboxSize
		local box = root.CFrame * CFrame.new(0, 0, -(reach / 2))
		local boxSize = Vector3.new(size.X, size.Y, reach)

		local params = OverlapParams.new()
		params.FilterType = Enum.RaycastFilterType.Exclude
		params.FilterDescendantsInstances = { character }
		params.MaxParts = 60

		local parts = workspace:GetPartBoundsInBox(box, boxSize, params)

		local seen = {}
		local victims = {}
		for _, part in ipairs(parts) do
			local model = part:FindFirstAncestorOfClass("Model")
			if model and not seen[model] then
				local humanoid = model:FindFirstChildOfClass("Humanoid")
				if humanoid and humanoid.Health > 0 then
					seen[model] = true
					table.insert(victims, model)
				end
			end
		end
		return victims
	end

	function CombatService.swing(player: Player, tool: Tool)
		local character = player.Character
		if not character then
			return
		end
		local humanoid = character:FindFirstChildOfClass("Humanoid")
		if not humanoid or humanoid.Health <= 0 then
			return
		end

		local s = stateFor(player)
		local now = os.clock()
		local cooldown = tool:GetAttribute("Cooldown") or 0.55
		if now - s.lastSwing < cooldown then
			return
		end
		s.lastSwing = now

		-- combo
		if now - s.comboAt <= Config.Combat.ComboWindow then
			s.combo = math.min(s.combo + 1, Config.Combat.ComboMaxStacks)
		else
			s.combo = 0
		end
		s.comboAt = now

		animateSwing(character, cooldown)

		local handle = tool:FindFirstChild("Handle") :: BasePart
		local trail = handle and handle:FindFirstChild("SwingTrail") :: Trail
		if trail then
			trail.Enabled = true
			task.delay(cooldown * 0.55, function()
				if trail.Parent then
					trail.Enabled = false
				end
			end)
		end
		if handle then
			Fx.impact(handle, 1.4 + math.random() * 0.2)
		end

		local reach = tool:GetAttribute("Reach") or 9
		local baseDamage = tool:GetAttribute("Damage") or 18
		local knockback = tool:GetAttribute("Knockback") or 55
		local critChance = tool:GetAttribute("Crit") or 0.08

		local comboMult = 1 + s.combo * Config.Combat.ComboDamagePerStack
		local crit = math.random() < critChance
		local damage = baseDamage * comboMult * (crit and 2 or 1)

		local origin = character:GetPivot().Position

		for _, victim in ipairs(hitscan(character, reach)) do
			if CombatService.canDamage(player, victim) then
				CombatService.damage(victim, damage, origin, knockback * (crit and 1.6 or 1), player)
				local _, victimRoot = Util.getRig(victim)
				if victimRoot then
					Fx.burst(victimRoot.Position, crit and Color3.fromRGB(255, 120, 80) or Color3.fromRGB(255, 230, 160),
						crit and 12 or 7, workspace)
					Fx.floatingText(victimRoot.Position + Vector3.new(0, 3, 0),
						(crit and "CRIT " or "") .. tostring(math.floor(damage)),
						crit and Color3.fromRGB(255, 140, 90) or Color3.fromRGB(255, 250, 220), workspace)
					Fx.impact(victimRoot, crit and 0.75 or 1)
				end
			end
		end
	end

	function CombatService.bind(player: Player, tool: Tool)
		tool.Activated:Connect(function()
			CombatService.swing(player, tool)
		end)
	end

	-- ─────────────────────────────────────────────────────────────────────────────
	-- lifecycle
	-- ─────────────────────────────────────────────────────────────────────────────

	function CombatService.onCharacter(player: Player, character: Model)
		local humanoid = character:WaitForChild("Humanoid", 10) :: Humanoid
		if not humanoid then
			return
		end
		humanoid.WalkSpeed = 19
		humanoid.JumpPower = 52
		humanoid.UseJumpPower = true

		task.wait(0.35)
		CombatService.equipCurrentBat(player)

		humanoid.Died:Connect(function()
			local killerTag = humanoid:FindFirstChild("creator") :: ObjectValue?
			if killerTag and killerTag.Value and killerTag.Value:IsA("Player") then
				CombatService.creditKill(killerTag.Value, player.Name)
			end
		end)
	end

	function CombatService.creditKill(player: Player, victimName: string)
		local profile = DataService.get(player)
		if not profile then
			return
		end
		profile.kills += 1
		Economy.push(player)
		Economy.notify(player, { kind = "ko", title = "KO!", body = victimName })
	end

	--- Used by NPCService so raider damage flows through the same path.
	function CombatService.npcAttack(npc: Model, victimModel: Model, damage: number)
		local _, npcRoot = Util.getRig(npc)
		if not npcRoot then
			return
		end
		CombatService.damage(victimModel, damage, npcRoot.Position, 28, nil)
	end

	function CombatService.start()
		Players.PlayerRemoving:Connect(function(player)
			state[player] = nil
		end)
	end

	return CombatService
end


__MODULES["DataService"] = function()
	--[[
		DataService.lua — DataStore persistence with retries, autosave and a
		safe shutdown flush. Falls back to in-memory only if DataStores are
		unavailable (Studio without API access), so the game still runs.
	]]

	local Req = __Req
	local Config = Req("Config")

	local DataStoreService = game:GetService("DataStoreService")
	local Players = game:GetService("Players")
	local RunService = game:GetService("RunService")

	local DataService = {}

	local STORE_NAME = "TungTungTycoon_v1"
	local AUTOSAVE_SECONDS = 90

	local store: DataStore? = nil
	local dataStoresUsable = true

	do
		local ok, result = pcall(function()
			return DataStoreService:GetDataStore(STORE_NAME)
		end)
		if ok then
			store = result
		else
			dataStoresUsable = false
			warn("[Tung] DataStores unavailable, running in memory-only mode: " .. tostring(result))
		end
	end

	local function defaultProfile()
		return {
			cash = Config.Economy.StartingCash,
			owned = {},        -- { [buttonId] = true }
			rebirths = 0,
			batTier = 1,
			kills = 0,
			playtime = 0,
			version = 1,
		}
	end

	local profiles: { [number]: any } = {}
	local loading: { [number]: boolean } = {}

	local function key(userId: number): string
		return "player_" .. userId
	end

	local function retry(fn, attempts: number)
		local lastErr
		for i = 1, attempts do
			local ok, result = pcall(fn)
			if ok then
				return true, result
			end
			lastErr = result
			task.wait(0.6 * i)
		end
		return false, lastErr
	end

	--- Merges saved fields onto a fresh default so schema additions are safe.
	local function reconcile(saved)
		local profile = defaultProfile()
		if type(saved) ~= "table" then
			return profile
		end
		for k, v in pairs(profile) do
			if saved[k] ~= nil and type(saved[k]) == type(v) then
				profile[k] = saved[k]
			end
		end
		-- prune ids that no longer exist in Config
		local cleanOwned = {}
		if type(profile.owned) == "table" then
			for id, value in pairs(profile.owned) do
				if value and Config.ButtonById[id] then
					cleanOwned[id] = true
				end
			end
		end
		profile.owned = cleanOwned
		profile.cash = math.max(0, tonumber(profile.cash) or 0)
		profile.rebirths = math.clamp(math.floor(tonumber(profile.rebirths) or 0), 0, Config.Rebirth.MaxRebirths)
		profile.batTier = math.clamp(math.floor(tonumber(profile.batTier) or 1), 1, #Config.Bats)
		return profile
	end

	function DataService.load(player: Player)
		local userId = player.UserId
		if profiles[userId] then
			return profiles[userId]
		end
		loading[userId] = true

		local profile
		if store and dataStoresUsable then
			local ok, saved = retry(function()
				return (store :: DataStore):GetAsync(key(userId))
			end, 4)
			if ok then
				profile = reconcile(saved)
			else
				warn(("[Tung] load failed for %s: %s"):format(player.Name, tostring(saved)))
				profile = reconcile(nil)
				profile.__loadFailed = true   -- never overwrite good data with a failed read
			end
		else
			profile = reconcile(nil)
			profile.__loadFailed = not dataStoresUsable
		end

		profiles[userId] = profile
		loading[userId] = nil
		return profile
	end

	function DataService.get(player: Player)
		return profiles[player.UserId]
	end

	function DataService.save(player: Player, release: boolean?)
		local userId = player.UserId
		local profile = profiles[userId]
		if not profile then
			return false
		end
		if profile.__loadFailed then
			-- data never loaded cleanly; refuse to clobber the real save
			if release then
				profiles[userId] = nil
			end
			return false
		end

		local payload = {
			cash = profile.cash,
			owned = profile.owned,
			rebirths = profile.rebirths,
			batTier = profile.batTier,
			kills = profile.kills,
			playtime = profile.playtime,
			version = profile.version,
		}

		local saved = false
		if store and dataStoresUsable then
			local ok, err = retry(function()
				return (store :: DataStore):UpdateAsync(key(userId), function()
					return payload
				end)
			end, 4)
			saved = ok
			if not ok then
				warn(("[Tung] save failed for %s: %s"):format(player.Name, tostring(err)))
			end
		end

		if release then
			profiles[userId] = nil
		end
		return saved
	end

	function DataService.start()
		Players.PlayerRemoving:Connect(function(player)
			DataService.save(player, true)
		end)

		task.spawn(function()
			while true do
				task.wait(AUTOSAVE_SECONDS)
				for _, player in ipairs(Players:GetPlayers()) do
					local profile = profiles[player.UserId]
					if profile then
						profile.playtime += AUTOSAVE_SECONDS
						task.spawn(DataService.save, player, false)
					end
				end
			end
		end)

		game:BindToClose(function()
			if RunService:IsStudio() then
				return
			end
			local remaining = 0
			for _, player in ipairs(Players:GetPlayers()) do
				remaining += 1
				task.spawn(function()
					DataService.save(player, true)
					remaining -= 1
				end)
			end
			local deadline = os.clock() + 25
			while remaining > 0 and os.clock() < deadline do
				task.wait(0.1)
			end
		end)
	end

	return DataService
end


__MODULES["Economy"] = function()
	--[[
		Economy.lua — the single place cash is created, spent and replicated.
		Everything else asks this module; nothing else touches profile.cash.
	]]

	local Req = __Req
	local Config = Req("Config")
	local Util = Req("Util")
	local Net = Req("Net")

	local Players = game:GetService("Players")

	local DataService = Req("DataService")

	local Economy = {}

	local statsRemote = Net.event("Stats")
	local notifyRemote = Net.event("Notify")

	local dirty: { [Player]: boolean } = {}

	function Economy.multiplier(player: Player): number
		local profile = DataService.get(player)
		if not profile then
			return 1
		end
		-- compounding, not linear: rebirth cost grows geometrically (CostGrowth^n)
		-- so a linear payout bonus would make each rebirth strictly worse than the
		-- last and the prestige loop would dead-end after two or three.
		return Config.Rebirth.MultiplierPerRebirth ^ profile.rebirths
	end

	function Economy.get(player: Player): number
		local profile = DataService.get(player)
		return profile and profile.cash or 0
	end

	function Economy.setupLeaderstats(player: Player)
		local profile = DataService.get(player)
		if not profile then
			return
		end

		local existing = player:FindFirstChild("leaderstats")
		if existing then
			existing:Destroy()
		end

		local folder = Instance.new("Folder")
		folder.Name = "leaderstats"
		folder.Parent = player

		local cash = Instance.new("NumberValue")
		cash.Name = Config.Economy.CurrencyName
		cash.Value = profile.cash
		cash.Parent = folder

		local rebirths = Instance.new("IntValue")
		rebirths.Name = "Rebirths"
		rebirths.Value = profile.rebirths
		rebirths.Parent = folder

		local kos = Instance.new("IntValue")
		kos.Name = "KOs"
		kos.Value = profile.kills
		kos.Parent = folder
	end

	local function syncLeaderstats(player: Player)
		local profile = DataService.get(player)
		local folder = player:FindFirstChild("leaderstats")
		if not profile or not folder then
			return
		end
		local cash = folder:FindFirstChild(Config.Economy.CurrencyName)
		if cash then
			(cash :: NumberValue).Value = profile.cash
		end
		local rebirths = folder:FindFirstChild("Rebirths")
		if rebirths then
			(rebirths :: IntValue).Value = profile.rebirths
		end
		local kos = folder:FindFirstChild("KOs")
		if kos then
			(kos :: IntValue).Value = profile.kills
		end
	end

	function Economy.push(player: Player)
		local profile = DataService.get(player)
		if not profile then
			return
		end
		syncLeaderstats(player)
		statsRemote:FireClient(player, {
			cash = profile.cash,
			rebirths = profile.rebirths,
			kills = profile.kills,
			batTier = profile.batTier,
			multiplier = Economy.multiplier(player),
			owned = profile.owned,
			rebirthCost = Economy.rebirthCost(player),
		})
	end

	--- Coalesces rapid-fire updates (droppers) into ~10 replications/sec.
	function Economy.markDirty(player: Player)
		dirty[player] = true
	end

	function Economy.add(player: Player, amount: number, applyMultiplier: boolean?)
		local profile = DataService.get(player)
		if not profile or amount <= 0 then
			return 0
		end
		local final = amount
		if applyMultiplier then
			final = amount * Economy.multiplier(player)
		end
		profile.cash += final
		Economy.markDirty(player)
		return final
	end

	function Economy.spend(player: Player, amount: number): boolean
		local profile = DataService.get(player)
		if not profile then
			return false
		end
		if profile.cash < amount then
			return false
		end
		profile.cash -= amount
		Economy.push(player)
		return true
	end

	--- Raiders nibble a slice of your bank when they land a hit.
	function Economy.steal(player: Player, fraction: number): number
		local profile = DataService.get(player)
		if not profile then
			return 0
		end
		local taken = math.floor(profile.cash * fraction)
		if taken <= 0 then
			return 0
		end
		profile.cash -= taken
		Economy.markDirty(player)
		return taken
	end

	function Economy.rebirthCost(player: Player): number
		local profile = DataService.get(player)
		local n = profile and profile.rebirths or 0
		return math.floor(Config.Rebirth.BaseCost * (Config.Rebirth.CostGrowth ^ n))
	end

	function Economy.notify(player: Player, payload)
		notifyRemote:FireClient(player, payload)
	end

	function Economy.start()
		task.spawn(function()
			while true do
				task.wait(0.1)
				for player in pairs(dirty) do
					dirty[player] = nil
					if player.Parent then
						Economy.push(player)
					end
				end
			end
		end)

		Players.PlayerRemoving:Connect(function(player)
			dirty[player] = nil
		end)
	end

	Economy.format = Util.abbreviate

	return Economy
end


