				self.lastPayoutFx = now
				Fx.floatingText(hit.Position + Vector3.new(0, 3, 0), "+" .. Util.abbreviate(gained), COLORS.gold, self.model)
				Fx.tung(hit, 0.9 + math.random() * 0.35, 0.18)
			end
		end
		model:Destroy()
	end

