__MODULES["Util"] = function()
	--[[ Util.lua — small helpers shared by client and server. ]]

	local Util = {}

	local SUFFIXES = {
		"", "K", "M", "B", "T", "Qa", "Qi", "Sx", "Sp", "Oc", "No",
		"Dc", "UDc", "DDc", "TDc", "QaDc", "QiDc", "SxDc", "SpDc", "OcDc", "NoDc", "Vg",
	}

	--- 1234567 -> "1.23M"
	function Util.abbreviate(n: number): string
		if n ~= n then return "0" end            -- NaN guard
		local sign = n < 0 and "-" or ""
		n = math.abs(n)
		if n < 1000 then
			return sign .. tostring(math.floor(n + 0.5))
		end
		local index = math.floor(math.log(n, 1000))
		index = math.clamp(index, 1, #SUFFIXES - 1)
		local scaled = n / (1000 ^ index)
		local text
		if scaled >= 100 then
			text = string.format("%.0f", scaled)
		elseif scaled >= 10 then
			text = string.format("%.1f", scaled)
		else
			text = string.format("%.2f", scaled)
		end
		-- Trim trailing zeros, but ONLY past a decimal point. Trimming
		-- unconditionally turns "320" into "32", i.e. 320K displays as 32K.
		if text:find("%.") then
			text = text:gsub("0+$", "")
			text = text:gsub("%.$", "")
		end
		return sign .. text .. SUFFIXES[index + 1]
	end

	--- 1234567 -> "1,234,567"
	function Util.comma(n: number): string
		local whole = string.format("%.0f", math.abs(n))
		local out = whole:reverse():gsub("(%d%d%d)", "%1,"):reverse()
		out = out:gsub("^,", "")
		return (n < 0 and "-" or "") .. out
	end

	function Util.weld(a: BasePart, b: BasePart, name: string?): WeldConstraint
		local weld = Instance.new("WeldConstraint")
		weld.Name = name or "TungWeld"
		weld.Part0 = a
		weld.Part1 = b
		weld.Parent = a
		return weld
	end

	--- Welds every descendant BasePart of `model` to `root` and anchors nothing.
	function Util.weldModel(model: Model, root: BasePart)
		for _, part in ipairs(model:GetDescendants()) do
			if part:IsA("BasePart") and part ~= root then
				part.Anchored = false
				Util.weld(root, part)
			end
		end
	end

	function Util.setCollision(model: Instance, group: string)
		for _, part in ipairs(model:GetDescendants()) do
			if part:IsA("BasePart") then
				part.CollisionGroup = group
			end
		end
		if model:IsA("BasePart") then
			model.CollisionGroup = group
		end
	end

	function Util.newPart(props: { [string]: any }): Part
		local part = Instance.new("Part")
		part.Anchored = true
		part.CanCollide = false
		part.CastShadow = false
		part.TopSurface = Enum.SurfaceType.Smooth
		part.BottomSurface = Enum.SurfaceType.Smooth
		for key, value in pairs(props) do
			if key ~= "Parent" then
				(part :: any)[key] = value
			end
		end
		if props.Parent then
			part.Parent = props.Parent
		end
		return part
	end

	function Util.roundedFrame(parent: Instance, radius: number): UICorner
		local corner = Instance.new("UICorner")
		corner.CornerRadius = UDim.new(0, radius)
		corner.Parent = parent
		return corner
	end

	function Util.shallowCopy(t)
		local out = {}
		for k, v in pairs(t) do
			out[k] = v
		end
		return out
	end

	function Util.count(t): number
		local n = 0
		for _ in pairs(t) do
			n += 1
		end
		return n
	end

	--- Deterministic-ish pseudo random from a string seed (used for plot flavour).
	function Util.hash(s: string): number
		local h = 5381
		for i = 1, #s do
			h = (h * 33 + s:byte(i)) % 2147483647
		end
		return h
	end

	function Util.lerpColor(a: Color3, b: Color3, t: number): Color3
		return a:Lerp(b, math.clamp(t, 0, 1))
	end

	--- Safely reads a character's humanoid + root, or nil.
	function Util.getRig(model: Instance?): (Humanoid?, BasePart?)
		if not model or not model:IsA("Model") then
			return nil, nil
		end
		local humanoid = model:FindFirstChildOfClass("Humanoid")
		local root = model:FindFirstChild("HumanoidRootPart")
		if humanoid and root and root:IsA("BasePart") then
			return humanoid, root
		end
		return nil, nil
	end

	return Util
end


__MODULES["CombatService"] = function()
	--[[
		CombatService.lua — bats, swinging, damage, knockback and PvP rules.

		Design notes
		  * The server is authoritative. Tool.Activated replicates, so the client
		    never gets to say "I hit them"; it only asks for a swing.
		  * PvP is opt-in by geography: you can only hurt another player while
		    BOTH of you are inside the arena ring. Your plot is a safe zone.
		  * Sahur raiders can be hit anywhere.
	]]

	local Req = __Req
	local Config = Req("Config")
	local Util = Req("Util")
	local Fx = Req("Fx")
	local Net = Req("Net")
	local TungModels = Req("TungModels")
	local DataService = Req("DataService")
	local Economy = Req("Economy")

	local Players = game:GetService("Players")
	local TweenService = game:GetService("TweenService")
	local Debris = game:GetService("Debris")

	local CombatService = {}

	local hitFeedback = Net.event("HitFeedback")
	local knockbackRemote = Net.event("Knockback")

	local state: { [Player]: { lastSwing: number, combo: number, comboAt: number } } = {}

	local function stateFor(player: Player)
		local s = state[player]
		if not s then
			s = { lastSwing = 0, combo = 0, comboAt = 0 }
			state[player] = s
		end
		return s
	end

	-- ─────────────────────────────────────────────────────────────────────────────
	-- zones
	-- ─────────────────────────────────────────────────────────────────────────────

	function CombatService.inArena(position: Vector3): boolean
		local flat = Vector3.new(position.X, 0, position.Z)
		return flat.Magnitude <= Config.World.ArenaRadius
	end

	--- Can `attacker` (a Player) hurt `victimModel`?
	function CombatService.canDamage(attacker: Player, victimModel: Model): boolean
		if victimModel:GetAttribute("IsSahurNPC") then
			return true
		end
		local victimPlayer = Players:GetPlayerFromCharacter(victimModel)
		if not victimPlayer then
			return false
		end
		if victimPlayer == attacker then
			return false
		end
		if not Config.Combat.ArenaPvP then
			return true
		end
		local attackerChar = attacker.Character
		if not attackerChar then
			return false
		end
		return CombatService.inArena(attackerChar:GetPivot().Position)
			and CombatService.inArena(victimModel:GetPivot().Position)
	end

	-- ─────────────────────────────────────────────────────────────────────────────
	-- bats
	-- ─────────────────────────────────────────────────────────────────────────────

	local function removeBats(container: Instance?)
		if not container then
			return
		end
		for _, child in ipairs(container:GetChildren()) do
			if child:IsA("Tool") and child:GetAttribute("BatId") then
				child:Destroy()
			end
		end
	end

	function CombatService.equipCurrentBat(player: Player)
		-- a character can spawn before the DataStore read finishes on first join
		local profile = DataService.get(player)
		local deadline = os.clock() + 12
		while not profile and player.Parent and os.clock() < deadline do
			task.wait(0.25)
			profile = DataService.get(player)
		end
		if not profile or not player.Parent then
			return
		end
		local tier = math.clamp(profile.batTier or 1, 1, #Config.Bats)
		local def = Config.Bats[tier]

		removeBats(player:FindFirstChildOfClass("Backpack"))
		removeBats(player.Character)

		local tool = TungModels.buildBatTool(def)
		-- straight into the Backpack: Roblox's own inventory + hotbar handles
		-- equipping, dropping and slot assignment, so we don't reimplement any of it
		tool.Parent = player:FindFirstChildOfClass("Backpack")

		CombatService.bind(player, tool)
	end

	function CombatService.grantBat(player: Player, batId: string)
		local def = Config.BatById[batId]
		local profile = DataService.get(player)
		if not def or not profile then
			return
		end
		if def.tier <= (profile.batTier or 1) then
			return
		end
		profile.batTier = def.tier
		CombatService.equipCurrentBat(player)
		Economy.push(player)
		Economy.notify(player, {
			kind = "gear",
			title = "NEW BAT: " .. def.name,
			body = ("%d damage  •  %.0f%% crit"):format(def.damage, def.crit * 100),
		})
	end

	-- ─────────────────────────────────────────────────────────────────────────────
	-- swinging
	-- ─────────────────────────────────────────────────────────────────────────────

	--- Swings the BAT and nothing else.
	---
	--- Tool.Grip is the offset of the built-in RightGrip weld between the hand and
	--- the Handle, so tweening it moves the bat within the hand. The character's
	--- arm keeps whatever pose Roblox's own Animate script gives it — we never
	--- touch the rig, play an animation, or override a limb.
	local function animateSwing(tool: Tool, duration: number)
		local base = tool:GetAttribute("BaseGrip")
		if typeof(base) ~= "CFrame" then
			base = tool.Grip
			tool:SetAttribute("BaseGrip", base)
		end

		local windUp = TweenService:Create(tool, TweenInfo.new(duration * 0.25, Enum.EasingStyle.Back, Enum.EasingDirection.Out), {
			Grip = base * CFrame.Angles(math.rad(-55), 0, 0),
		})
		local strike = TweenService:Create(tool, TweenInfo.new(duration * 0.28, Enum.EasingStyle.Quart, Enum.EasingDirection.Out), {
			Grip = base * CFrame.Angles(math.rad(95), 0, math.rad(20)),
		})
		local reset = TweenService:Create(tool, TweenInfo.new(duration * 0.45, Enum.EasingStyle.Quad, Enum.EasingDirection.Out), {
			Grip = base,
		})

		windUp:Play()
		windUp.Completed:Once(function()
			strike:Play()
			strike.Completed:Once(function()
				reset:Play()
			end)
		end)
	end

	--- Applies damage to any humanoid, from a player or from an NPC.
	function CombatService.damage(victimModel: Model, amount: number, sourcePosition: Vector3?, knockback: number?, attacker: Player?)
		local humanoid, root = Util.getRig(victimModel)
		if not humanoid or not root or humanoid.Health <= 0 then
			return false
		end

		-- classic "creator" tag so whoever landed the last hit gets the credit
		if attacker then
			local old = humanoid:FindFirstChild("creator")
			if old then
				old:Destroy()
			end
			local tag = Instance.new("ObjectValue")
			tag.Name = "creator"
			tag.Value = attacker
			tag.Parent = humanoid
			Debris:AddItem(tag, 8)
		end

		humanoid:TakeDamage(amount)

		if knockback and knockback > 0 and sourcePosition then
			local direction = (root.Position - sourcePosition)
			direction = Vector3.new(direction.X, 0, direction.Z)
			if direction.Magnitude < 0.1 then
				direction = Vector3.new(0, 0, 1)
			end
			direction = direction.Unit
			local impulse = (direction * knockback + Vector3.new(0, knockback * 0.45, 0)) * root.AssemblyMass * 0.6

			local victimPlayer = Players:GetPlayerFromCharacter(victimModel)
			if victimPlayer then
				-- The victim's own client owns their character's physics, so a
				-- server-side ApplyImpulse is overwritten on the next replication
				-- tick. Ask the owning client to apply it instead.
				knockbackRemote:FireClient(victimPlayer, impulse)
			else
				root:ApplyImpulse(impulse)
			end
		end

		if attacker then
			hitFeedback:FireClient(attacker, {
				damage = amount,
				position = root.Position,
				killed = humanoid.Health <= 0,
			})
		end
		return true
	end

	local function hitscan(character: Model, reach: number): { Model }
		local root = character:FindFirstChild("HumanoidRootPart") :: BasePart
		if not root then
			return {}
		end
		local size = Config.Combat.HitboxSize
		local box = root.CFrame * CFrame.new(0, 0, -(reach / 2))
		local boxSize = Vector3.new(size.X, size.Y, reach)

		local params = OverlapParams.new()
		params.FilterType = Enum.RaycastFilterType.Exclude
		params.FilterDescendantsInstances = { character }
		params.MaxParts = 60

		local parts = workspace:GetPartBoundsInBox(box, boxSize, params)

		local seen = {}
		local victims = {}
		for _, part in ipairs(parts) do
			local model = part:FindFirstAncestorOfClass("Model")
			if model and not seen[model] then
				local humanoid = model:FindFirstChildOfClass("Humanoid")
				if humanoid and humanoid.Health > 0 then
					seen[model] = true
					table.insert(victims, model)
				end
			end
		end
		return victims
	end

	function CombatService.swing(player: Player, tool: Tool)
		local character = player.Character
		if not character then
			return
		end
		local humanoid = character:FindFirstChildOfClass("Humanoid")
		if not humanoid or humanoid.Health <= 0 then
			return
		end

		local s = stateFor(player)
		local now = os.clock()
		local cooldown = tool:GetAttribute("Cooldown") or 0.55
		if now - s.lastSwing < cooldown then
			return
		end
		s.lastSwing = now

		-- combo
		if now - s.comboAt <= Config.Combat.ComboWindow then
			s.combo = math.min(s.combo + 1, Config.Combat.ComboMaxStacks)
		else
			s.combo = 0
		end
		s.comboAt = now

		animateSwing(tool, cooldown)

		local handle = tool:FindFirstChild("Handle") :: BasePart
		local trail = handle and handle:FindFirstChild("SwingTrail") :: Trail
		if trail then
			trail.Enabled = true
			task.delay(cooldown * 0.55, function()
				if trail.Parent then
					trail.Enabled = false
				end
			end)
		end
		if handle then
			Fx.impact(handle, 1.4 + math.random() * 0.2)
		end

		local reach = tool:GetAttribute("Reach") or 9
		local baseDamage = tool:GetAttribute("Damage") or 18
		local knockback = tool:GetAttribute("Knockback") or 55
		local critChance = tool:GetAttribute("Crit") or 0.08

		local comboMult = 1 + s.combo * Config.Combat.ComboDamagePerStack
		local crit = math.random() < critChance
		local damage = baseDamage * comboMult * (crit and 2 or 1)

		local origin = character:GetPivot().Position

		for _, victim in ipairs(hitscan(character, reach)) do
			if CombatService.canDamage(player, victim) then
				CombatService.damage(victim, damage, origin, knockback * (crit and 1.6 or 1), player)
				local _, victimRoot = Util.getRig(victim)
				if victimRoot then
					Fx.burst(victimRoot.Position, crit and Color3.fromRGB(255, 120, 80) or Color3.fromRGB(255, 230, 160),
						crit and 12 or 7, workspace)
					Fx.floatingText(victimRoot.Position + Vector3.new(0, 3, 0),
						(crit and "CRIT " or "") .. tostring(math.floor(damage)),
						crit and Color3.fromRGB(255, 140, 90) or Color3.fromRGB(255, 250, 220), workspace)
					Fx.impact(victimRoot, crit and 0.75 or 1)
				end
			end
		end
	end

	function CombatService.bind(player: Player, tool: Tool)
		tool.Activated:Connect(function()
			CombatService.swing(player, tool)
		end)
	end

	-- ─────────────────────────────────────────────────────────────────────────────
	-- lifecycle
	-- ─────────────────────────────────────────────────────────────────────────────

	function CombatService.onCharacter(player: Player, character: Model)
		local humanoid = character:WaitForChild("Humanoid", 10) :: Humanoid
		if not humanoid then
			return
		end
		humanoid.WalkSpeed = 19
		humanoid.JumpPower = 52
		humanoid.UseJumpPower = true

		task.wait(0.35)
		CombatService.equipCurrentBat(player)

		humanoid.Died:Connect(function()
			local killerTag = humanoid:FindFirstChild("creator") :: ObjectValue?
			if killerTag and killerTag.Value and killerTag.Value:IsA("Player") then
				CombatService.creditKill(killerTag.Value, player.Name)
			end
		end)
	end

	function CombatService.creditKill(player: Player, victimName: string)
		local profile = DataService.get(player)
		if not profile then
			return
		end
		profile.kills += 1
		Economy.push(player)
		Economy.notify(player, { kind = "ko", title = "KO!", body = victimName })
	end

	--- Used by NPCService so raider damage flows through the same path.
	function CombatService.npcAttack(npc: Model, victimModel: Model, damage: number)
		local _, npcRoot = Util.getRig(npc)
		if not npcRoot then
			return
		end
		CombatService.damage(victimModel, damage, npcRoot.Position, 28, nil)
	end

	function CombatService.start()
		Players.PlayerRemoving:Connect(function(player)
			state[player] = nil
		end)
	end

	return CombatService
end


__MODULES["DataService"] = function()
	--[[
		DataService.lua — DataStore persistence with retries, autosave and a
		safe shutdown flush. Falls back to in-memory only if DataStores are
		unavailable (Studio without API access), so the game still runs.
	]]

	local Req = __Req
	local Config = Req("Config")

	local DataStoreService = game:GetService("DataStoreService")
	local Players = game:GetService("Players")
	local RunService = game:GetService("RunService")

	local DataService = {}

	local STORE_NAME = "TungTungTycoon_v1"
	local AUTOSAVE_SECONDS = 90

	local store: DataStore? = nil
	local dataStoresUsable = true

	do
		local ok, result = pcall(function()
			return DataStoreService:GetDataStore(STORE_NAME)
		end)
		if ok then
			store = result
		else
			dataStoresUsable = false
			warn("[Tung] DataStores unavailable, running in memory-only mode: " .. tostring(result))
		end
	end

	local function defaultProfile()
		return {
			cash = Config.Economy.StartingCash,
			owned = {},        -- { [buttonId] = true }
			rebirths = 0,
			batTier = 1,
			kills = 0,
			playtime = 0,
			version = 1,
		}
	end

	local profiles: { [number]: any } = {}
	local loading: { [number]: boolean } = {}

	local function key(userId: number): string
		return "player_" .. userId
	end

	local function retry(fn, attempts: number)
		local lastErr
		for i = 1, attempts do
			local ok, result = pcall(fn)
			if ok then
				return true, result
			end
			lastErr = result
			task.wait(0.6 * i)
		end
		return false, lastErr
	end

	--- Merges saved fields onto a fresh default so schema additions are safe.
	local function reconcile(saved)
		local profile = defaultProfile()
		if type(saved) ~= "table" then
			return profile
		end
		for k, v in pairs(profile) do
			if saved[k] ~= nil and type(saved[k]) == type(v) then
				profile[k] = saved[k]
			end
		end
		-- prune ids that no longer exist in Config
		local cleanOwned = {}
		if type(profile.owned) == "table" then
			for id, value in pairs(profile.owned) do
				if value and Config.ButtonById[id] then
					cleanOwned[id] = true
				end
			end
		end
		profile.owned = cleanOwned
		profile.cash = math.max(0, tonumber(profile.cash) or 0)
		profile.rebirths = math.clamp(math.floor(tonumber(profile.rebirths) or 0), 0, Config.Rebirth.MaxRebirths)
		profile.batTier = math.clamp(math.floor(tonumber(profile.batTier) or 1), 1, #Config.Bats)
		return profile
	end

	function DataService.load(player: Player)
		local userId = player.UserId
		if profiles[userId] then
			return profiles[userId]
		end
		loading[userId] = true

		local profile
		if store and dataStoresUsable then
			local ok, saved = retry(function()
				return (store :: DataStore):GetAsync(key(userId))
			end, 4)
			if ok then
				profile = reconcile(saved)
			else
				warn(("[Tung] load failed for %s: %s"):format(player.Name, tostring(saved)))
				profile = reconcile(nil)
				profile.__loadFailed = true   -- never overwrite good data with a failed read
			end
		else
			profile = reconcile(nil)
			profile.__loadFailed = not dataStoresUsable
		end

		profiles[userId] = profile
		loading[userId] = nil
		return profile
	end

	function DataService.get(player: Player)
		return profiles[player.UserId]
	end

	function DataService.save(player: Player, release: boolean?)
		local userId = player.UserId
		local profile = profiles[userId]
		if not profile then
			return false
		end
		if profile.__loadFailed then
			-- data never loaded cleanly; refuse to clobber the real save
			if release then
				profiles[userId] = nil
			end
			return false
		end

		local payload = {
			cash = profile.cash,
			owned = profile.owned,
			rebirths = profile.rebirths,
			batTier = profile.batTier,
			kills = profile.kills,
			playtime = profile.playtime,
			version = profile.version,
		}

		local saved = false
		if store and dataStoresUsable then
			local ok, err = retry(function()
				return (store :: DataStore):UpdateAsync(key(userId), function()
					return payload
				end)
			end, 4)
			saved = ok
			if not ok then
				warn(("[Tung] save failed for %s: %s"):format(player.Name, tostring(err)))
			end
		end

		if release then
			profiles[userId] = nil
		end
		return saved
	end

	function DataService.start()
		Players.PlayerRemoving:Connect(function(player)
			DataService.save(player, true)
		end)

		task.spawn(function()
			while true do
				task.wait(AUTOSAVE_SECONDS)
				for _, player in ipairs(Players:GetPlayers()) do
					local profile = profiles[player.UserId]
					if profile then
						profile.playtime += AUTOSAVE_SECONDS
						task.spawn(DataService.save, player, false)
					end
				end
			end
		end)

		game:BindToClose(function()
			if RunService:IsStudio() then
				return
			end
			local remaining = 0
			for _, player in ipairs(Players:GetPlayers()) do
				remaining += 1
				task.spawn(function()
					DataService.save(player, true)
					remaining -= 1
				end)
			end
			local deadline = os.clock() + 25
			while remaining > 0 and os.clock() < deadline do
				task.wait(0.1)
			end
		end)
	end

	return DataService
end


__MODULES["Economy"] = function()
	--[[
		Economy.lua — the single place cash is created, spent and replicated.
		Everything else asks this module; nothing else touches profile.cash.
	]]

	local Req = __Req
	local Config = Req("Config")
	local Util = Req("Util")
	local Net = Req("Net")

	local Players = game:GetService("Players")

	local DataService = Req("DataService")

	local Economy = {}

	local statsRemote = Net.event("Stats")
	local notifyRemote = Net.event("Notify")

	local dirty: { [Player]: boolean } = {}

	function Economy.multiplier(player: Player): number
		local profile = DataService.get(player)
		if not profile then
			return 1
		end
		-- compounding, not linear: rebirth cost grows geometrically (CostGrowth^n)
		-- so a linear payout bonus would make each rebirth strictly worse than the
		-- last and the prestige loop would dead-end after two or three.
		return Config.Rebirth.MultiplierPerRebirth ^ profile.rebirths
	end

	function Economy.get(player: Player): number
		local profile = DataService.get(player)
		return profile and profile.cash or 0
	end

	function Economy.setupLeaderstats(player: Player)
		local profile = DataService.get(player)
		if not profile then
			return
		end

		local existing = player:FindFirstChild("leaderstats")
		if existing then
			existing:Destroy()
		end

		local folder = Instance.new("Folder")
		folder.Name = "leaderstats"
		folder.Parent = player

		local cash = Instance.new("NumberValue")
		cash.Name = Config.Economy.CurrencyName
		cash.Value = profile.cash
		cash.Parent = folder

		local rebirths = Instance.new("IntValue")
		rebirths.Name = "Rebirths"
		rebirths.Value = profile.rebirths
		rebirths.Parent = folder

		local kos = Instance.new("IntValue")
		kos.Name = "KOs"
		kos.Value = profile.kills
		kos.Parent = folder
	end

	local function syncLeaderstats(player: Player)
		local profile = DataService.get(player)
		local folder = player:FindFirstChild("leaderstats")
		if not profile or not folder then
			return
		end
		local cash = folder:FindFirstChild(Config.Economy.CurrencyName)
		if cash then
			(cash :: NumberValue).Value = profile.cash
		end
		local rebirths = folder:FindFirstChild("Rebirths")
		if rebirths then
			(rebirths :: IntValue).Value = profile.rebirths
		end
		local kos = folder:FindFirstChild("KOs")
		if kos then
			(kos :: IntValue).Value = profile.kills
		end
	end

	function Economy.push(player: Player)
		local profile = DataService.get(player)
		if not profile then
			return
		end
		syncLeaderstats(player)
		statsRemote:FireClient(player, {
			cash = profile.cash,
			rebirths = profile.rebirths,
			kills = profile.kills,
			batTier = profile.batTier,
			multiplier = Economy.multiplier(player),
			owned = profile.owned,
			rebirthCost = Economy.rebirthCost(player),
		})
	end

	--- Coalesces rapid-fire updates (droppers) into ~10 replications/sec.
	function Economy.markDirty(player: Player)
		dirty[player] = true
	end

	function Economy.add(player: Player, amount: number, applyMultiplier: boolean?)
		local profile = DataService.get(player)
		if not profile or amount <= 0 then
			return 0
		end
		local final = amount
		if applyMultiplier then
			final = amount * Economy.multiplier(player)
		end
		profile.cash += final
		Economy.markDirty(player)
		return final
	end

	function Economy.spend(player: Player, amount: number): boolean
		local profile = DataService.get(player)
		if not profile then
			return false
		end
		if profile.cash < amount then
			return false
		end
		profile.cash -= amount
		Economy.push(player)
		return true
	end

	--- Raiders nibble a slice of your bank when they land a hit.
	function Economy.steal(player: Player, fraction: number): number
		local profile = DataService.get(player)
		if not profile then
			return 0
		end
		local taken = math.floor(profile.cash * fraction)
		if taken <= 0 then
			return 0
		end
		profile.cash -= taken
		Economy.markDirty(player)
		return taken
	end

	function Economy.rebirthCost(player: Player): number
		local profile = DataService.get(player)
		local n = profile and profile.rebirths or 0
		return math.floor(Config.Rebirth.BaseCost * (Config.Rebirth.CostGrowth ^ n))
	end

	function Economy.notify(player: Player, payload)
		notifyRemote:FireClient(player, payload)
	end

	function Economy.start()
		task.spawn(function()
			while true do
				task.wait(0.1)
				for player in pairs(dirty) do
					dirty[player] = nil
					if player.Parent then
						Economy.push(player)
					end
				end
			end
		end)

		Players.PlayerRemoving:Connect(function(player)
			dirty[player] = nil
		end)
	end

	Economy.format = Util.abbreviate

	return Economy
end


__MODULES["MapBuilder"] = function()
	--[[
		MapBuilder.lua — generates the whole world at runtime.

		Layout: a central open-air arena (PvP + raid target) ringed by
		Config.World.PlotCount tycoon plots, each rotated to face inward.
	]]

	local Req = __Req
	local Config = Req("Config")
	local Util = Req("Util")
	local TungModels = Req("TungModels")

	local Lighting = game:GetService("Lighting")

	local MapBuilder = {}

	local W = Config.World

	local PALETTE = {
		ground   = Color3.fromRGB(106, 168, 79),   -- grass
		pad      = Color3.fromRGB(199, 195, 185),  -- light concrete
		padEdge  = Color3.fromRGB(255, 176, 60),   -- warm marker stripe
		arena    = Color3.fromRGB(178, 172, 160),
		arenaLip = Color3.fromRGB(255, 140, 40),
		wood     = Color3.fromRGB(150, 103, 60),
	}

	local function newPart(parent, name, size, cf, color, material)
		local p = Instance.new("Part")
		p.Name = name
		p.Size = size
		p.CFrame = cf
		p.Color = color
		p.Material = material or Enum.Material.SmoothPlastic
		p.Anchored = true
		p.CanCollide = true
		p.TopSurface = Enum.SurfaceType.Smooth
		p.BottomSurface = Enum.SurfaceType.Smooth
		p.Parent = parent
		return p
	end

	--- Stock Roblox daylight. Deliberately plain: bright, neutral and readable.
	function MapBuilder.applyLighting()
		-- Lighting.Technology is not script-writable at runtime; it is set in
		-- default.project.json instead. Guarded so a manual/paste-in install
		-- doesn't take the whole boot sequence down with it.
		pcall(function()
			Lighting.Technology = Enum.Technology.ShadowMap
		end)
		Lighting.Ambient = Color3.fromRGB(0, 0, 0)
		Lighting.OutdoorAmbient = Color3.fromRGB(128, 128, 128)
		Lighting.Brightness = 3
		Lighting.ClockTime = 14.5
		Lighting.GeographicLatitude = 41.733
		Lighting.ExposureCompensation = 0
		Lighting.EnvironmentDiffuseScale = 1
		Lighting.EnvironmentSpecularScale = 1
		Lighting.FogColor = Color3.fromRGB(192, 192, 192)
		Lighting.FogStart = 0
		Lighting.FogEnd = 100000
		Lighting.GlobalShadows = true

		-- strip anything a previous (darker) build left behind, so re-running
		-- doesn't stack post-effects
		for _, existing in ipairs(Lighting:GetChildren()) do
			if existing:IsA("Atmosphere") or existing:IsA("PostEffect") then
				existing:Destroy()
			end
		end
	end

	--- Returns the CFrame for plot `index` (1-based). +Z of the CFrame points
	--- at the arena, matching the plot-local layout in Config.
	function MapBuilder.plotCFrame(index: number): CFrame
		local placement = W.PlotPlacements[index] or W.PlotPlacements[1]
		local angle, radius = placement.angle, placement.radius
		-- y = PlotSurfaceY, so plot-local y=0 is the top of the pad and sits
		-- clear of the ground plane instead of z-fighting with it
		local position = Vector3.new(math.sin(angle) * radius, W.PlotSurfaceY, math.cos(angle) * radius)
		-- look at the origin, then flip so plot-local +Z faces the arena
		local look = CFrame.lookAt(position, Vector3.new(0, 0, 0))
		return look * CFrame.Angles(0, math.pi, 0)
	end

	-- MVP arena: a floor, a low plinth, the statue and a sign. The torches, the
	-- 32-segment glowing rim and the 72-tile ring path were all decoration with
	-- no gameplay attached, so they are gone.
	local function buildArena(parent: Instance)
		local arena = Instance.new("Model")
		arena.Name = "Arena"
		arena.Parent = parent

		local floorThickness = 3
		local floor = newPart(arena, "ArenaFloor", Vector3.new(floorThickness, W.ArenaRadius * 2, W.ArenaRadius * 2),
			CFrame.new(0, W.ArenaFloorTopY - floorThickness / 2, 0) * CFrame.Angles(0, 0, math.pi / 2),
			PALETTE.arena, Enum.Material.Pebble)
		floor.Shape = Enum.PartType.Cylinder

		-- single ring border instead of 32 separate segments
		local rim = newPart(arena, "Rim", Vector3.new(1.2, W.ArenaRadius * 2 + 6, W.ArenaRadius * 2 + 6),
			CFrame.new(0, W.ArenaFloorTopY - 0.4, 0) * CFrame.Angles(0, 0, math.pi / 2),
			PALETTE.arenaLip, Enum.Material.Neon)
		rim.Shape = Enum.PartType.Cylinder
		rim.CanCollide = false

		local daisHeight = 4
		local daisTopY = W.ArenaFloorTopY + daisHeight
		local dais = newPart(arena, "Dais", Vector3.new(daisHeight, 26, 26),
			CFrame.new(0, daisTopY - daisHeight / 2, 0) * CFrame.Angles(0, 0, math.pi / 2),
			PALETTE.pad, Enum.Material.Slate)
		dais.Shape = Enum.PartType.Cylinder

		-- The statue's feet are 2.85 * scale below its pivot (see TungModels), and
		-- the infinity variant carries its own 1.5x scale. Stand it ON the dais
		-- instead of guessing a height and burying its legs in the platform.
		local statueScale = 3.5
		local footDrop = 2.85 * statueScale * Config.Variants.infinity.scale
		local statue = TungModels.buildStatue("infinity", statueScale)
		statue.Name = "ArenaStatue"
		statue:PivotTo(CFrame.new(0, daisTopY + footDrop, 0))
		statue.Parent = arena

		local sign = newPart(arena, "TitleAnchor", Vector3.new(1, 1, 1), CFrame.new(0, 34, 0), PALETTE.pad)
		sign.Transparency = 1
		sign.CanCollide = false

		local billboard = Instance.new("BillboardGui")
		billboard.Size = UDim2.fromScale(56, 14)
		billboard.MaxDistance = 900
		billboard.Parent = sign

		local title = Instance.new("TextLabel")
		title.BackgroundTransparency = 1
		title.Size = UDim2.fromScale(1, 0.62)
		title.Font = Enum.Font.FredokaOne
		title.Text = "TUNG TUNG TYCOON"
		title.TextColor3 = Color3.fromRGB(255, 214, 90)
		title.TextStrokeColor3 = Color3.fromRGB(46, 32, 16)
		title.TextStrokeTransparency = 0.1
		title.TextScaled = true
		title.Parent = billboard

		local subtitle = Instance.new("TextLabel")
		subtitle.BackgroundTransparency = 1
		subtitle.Position = UDim2.fromScale(0, 0.62)
		subtitle.Size = UDim2.fromScale(1, 0.34)
		subtitle.Font = Enum.Font.GothamMedium
		subtitle.Text = "pvp enabled inside the ring"
		subtitle.TextColor3 = Color3.fromRGB(255, 255, 255)
		subtitle.TextStrokeColor3 = Color3.fromRGB(46, 32, 16)
		subtitle.TextStrokeTransparency = 0.4
		subtitle.TextScaled = true
		subtitle.Parent = billboard

		return arena
	end

	local function buildSpawn(parent: Instance)
		local spawnPad = Instance.new("SpawnLocation")
		spawnPad.Name = "TungSpawn"
		spawnPad.Size = Vector3.new(36, 1.5, 24)
		-- in FRONT of the dais, not on top of it: spawning at the origin puts
		-- players inside the statue's legs
		spawnPad.CFrame = CFrame.new(0, W.ArenaFloorTopY + 0.75, 52)
		spawnPad.Anchored = true
		spawnPad.CanCollide = true
		spawnPad.Color = Color3.fromRGB(150, 103, 60)
		spawnPad.Material = Enum.Material.WoodPlanks
		spawnPad.TopSurface = Enum.SurfaceType.Smooth
		spawnPad.Duration = 0
		spawnPad.Neutral = true
		spawnPad.Parent = parent
		return spawnPad
	end

	function MapBuilder.build(): Folder
		local existing = workspace:FindFirstChild("TungWorld")
		if existing then
			existing:Destroy()
		end

		-- clear the default baseplate if the place still has one
		local defaultBase = workspace:FindFirstChild("Baseplate")
		if defaultBase then
			defaultBase:Destroy()
		end

		local world = Instance.new("Folder")
		world.Name = "TungWorld"
		world.Parent = workspace

		local groundThickness = 12
		local ground = newPart(world, "Ground", Vector3.new(W.BaseplateSize, groundThickness, W.BaseplateSize),
			CFrame.new(0, W.GroundTopY - groundThickness / 2, 0), PALETTE.ground, Enum.Material.Grass)
		ground.Anchored = true

		buildArena(world)
		buildSpawn(world)

		local plots = Instance.new("Folder")
		plots.Name = "Plots"
		plots.Parent = world

		MapBuilder.applyLighting()

		return world
	end

	--- Builds the flat pad + signage for one plot. The tycoon machinery is added
	--- later by Tycoon.lua; this is just the real estate.
	function MapBuilder.buildPlotPad(parent: Instance, index: number): (Model, CFrame)
		local cf = MapBuilder.plotCFrame(index)

		local model = Instance.new("Model")
		model.Name = "Plot" .. index
		model.Parent = parent

		local pad = newPart(model, "Pad", W.PlotSize, cf * CFrame.new(0, -W.PlotSize.Y / 2, 0), PALETTE.pad, Enum.Material.Concrete)
		pad:SetAttribute("PlotIndex", index)

		-- glowing border. The pad is no longer square, so the front/back strips key
		-- off half the DEPTH and the side strips off half the width; using one
		-- `half` for both left the front and back edges floating inside the pad.
		local half = W.PlotSize.X / 2
		local halfZ = W.PlotSize.Z / 2
		local edges = {
			{ Vector3.new(W.PlotSize.X, 1, 2), CFrame.new(0, 0.2, halfZ) },
			{ Vector3.new(W.PlotSize.X, 1, 2), CFrame.new(0, 0.2, -halfZ) },
			{ Vector3.new(2, 1, W.PlotSize.Z), CFrame.new(half, 0.2, 0) },
			{ Vector3.new(2, 1, W.PlotSize.Z), CFrame.new(-half, 0.2, 0) },
		}
		for i, edge in ipairs(edges) do
			local e = newPart(model, "Edge" .. i, edge[1], cf * edge[2], PALETTE.padEdge, Enum.Material.Neon)
			e.CanCollide = false
		end

		-- Claim totem, parked in the front-RIGHT corner. It used to stand at x = 0,
		-- directly on top of the pad you are meant to step on, and then in the
		-- front-left corner, which is where Tycoon builds the vault — the two
		-- models were interpenetrating on every plot.
		local totemCF = cf * CFrame.new(half - 12, 6, halfZ - 8)
		local totem = newPart(model, "Totem", Vector3.new(4, 12, 4), totemCF, Color3.fromRGB(70, 52, 40), Enum.Material.Wood)
		totem:SetAttribute("PlotIndex", index)

		local billboard = Instance.new("BillboardGui")
		billboard.Name = "Sign"
		billboard.Size = UDim2.fromScale(26, 9)
		billboard.StudsOffsetWorldSpace = Vector3.new(0, 9, 0)
		billboard.MaxDistance = 500
		billboard.AlwaysOnTop = false
		billboard.Parent = totem

		local frame = Instance.new("Frame")
		frame.Size = UDim2.fromScale(1, 1)
		frame.BackgroundColor3 = Color3.fromRGB(24, 18, 34)
		frame.BackgroundTransparency = 0.25
		frame.BorderSizePixel = 0
		frame.Parent = billboard
		Util.roundedFrame(frame, 12)

		local stroke = Instance.new("UIStroke")
		stroke.Color = PALETTE.padEdge
		stroke.Thickness = 3
		stroke.Parent = frame

		local label = Instance.new("TextLabel")
		label.Name = "Owner"
		label.BackgroundTransparency = 1
		label.Size = UDim2.fromScale(0.92, 0.9)
		label.Position = UDim2.fromScale(0.04, 0.05)
		label.Font = Enum.Font.FredokaOne
		label.Text = "UNCLAIMED PLOT " .. index .. "\nstep on the pad to claim"
		label.TextColor3 = Color3.fromRGB(255, 236, 180)
		label.TextScaled = true
		label.Parent = frame

		return model, cf
	end

	return MapBuilder
end


__MODULES["NPCService"] = function()
	--[[
		NPCService.lua — the Sahur Raid.

		Every few minutes a wave of Tung Tung Tung Sahur raiders spawns at the
		arena rim and goes looking for players. They hit hard, they nibble your
		bank, and they pay out well when you knock them down.

		All NPCs are ticked from one loop rather than a thread each.
	]]

	local Req = __Req
	local Config = Req("Config")
	local Util = Req("Util")
	local Fx = Req("Fx")
	local Net = Req("Net")
	local TungModels = Req("TungModels")
	local Economy = Req("Economy")
	local DataService = Req("DataService")
	local CombatService = Req("CombatService")

	local Players = game:GetService("Players")
	local Debris = game:GetService("Debris")

	local NPCService = {}

	local waveRemote = Net.event("WaveState")
	local notifyRemote = Net.event("Notify")

	local WV = Config.Waves

	local active: { [Model]: any } = {}
	local folder: Folder
	local waveNumber = 0
	local aliveCount = 0

	-- raider flavour escalates with the wave number
	local WAVE_VARIANTS = { "classic", "oak", "ash", "crimson", "neon", "void", "eclipse", "galaxy", "infinity" }

	local function variantForWave(wave: number, boss: boolean): string
		local index = math.clamp(math.floor((wave - 1) / 2) + 1, 1, #WAVE_VARIANTS)
		if boss then
			index = math.clamp(index + 2, 1, #WAVE_VARIANTS)
		end
		return WAVE_VARIANTS[index]
	end

	local function broadcast(payload)
		waveRemote:FireAllClients(payload)
	end

	-- ─────────────────────────────────────────────────────────────────────────────

	local function nearestPlayer(position: Vector3, maxDistance: number): (Player?, Model?, number)
		local bestPlayer, bestChar, bestDistance = nil, nil, maxDistance
		for _, player in ipairs(Players:GetPlayers()) do
			local character = player.Character
			local humanoid = character and character:FindFirstChildOfClass("Humanoid")
			if character and humanoid and humanoid.Health > 0 then
				local distance = (character:GetPivot().Position - position).Magnitude
				if distance < bestDistance then
					bestPlayer, bestChar, bestDistance = player, character, distance
				end
			end
		end
		return bestPlayer, bestChar, bestDistance
	end

	local function killReward(wave: number, boss: boolean): number
		local reward = WV.RewardBase * (WV.RewardGrowth ^ (wave - 1))
		if boss then
			reward *= WV.BossHealthMultiplier
		end
		return math.floor(reward)
	end

	local function onRaiderDied(npc: Model, entry)
		if entry.dead then
			return
		end
		entry.dead = true
		aliveCount = math.max(0, aliveCount - 1)

		local humanoid = npc:FindFirstChildOfClass("Humanoid")
		local tag = humanoid and humanoid:FindFirstChild("creator") :: ObjectValue?
		local killer = tag and tag.Value

		local pivot = npc:GetPivot().Position
		local variant = Config.Variants[npc:GetAttribute("Variant") or "classic"] or Config.Variants.classic
		Fx.burst(pivot, variant.wood, entry.boss and 40 or 18, workspace)

		if killer and killer:IsA("Player") and killer.Parent then
			local reward = killReward(entry.wave, entry.boss)
			local gained = Economy.add(killer, reward, true)
			local profile = DataService.get(killer)
			if profile then
				profile.kills += 1
			end
			Economy.push(killer)
			Fx.floatingText(pivot + Vector3.new(0, 6, 0), "+" .. Util.abbreviate(gained), Color3.fromRGB(255, 205, 90), workspace)
			if entry.boss then
				notifyRemote:FireAllClients({
					kind = "boss",
					title = "BOSS DOWN",
					body = ("%s finished the wave %d boss."):format(killer.DisplayName, entry.wave),
				})
			end
		end

		-- flop over, then clean up
		for _, part in ipairs(npc:GetDescendants()) do
			if part:IsA("Motor6D") then
				part.Enabled = false
			end
		end
		Debris:AddItem(npc, 4)
		active[npc] = nil

		if aliveCount <= 0 then
			broadcast({ phase = "clear", wave = waveNumber, remaining = 0 })
		else
			broadcast({ phase = "active", wave = waveNumber, remaining = aliveCount })
		end
	end

	local function spawnRaider(wave: number, index: number, count: number, boss: boolean)
		local variantName = variantForWave(wave, boss)
		local health = WV.BaseHealth * (WV.HealthGrowth ^ (wave - 1)) * (boss and WV.BossHealthMultiplier or 1)
		local damage = math.min(
			WV.BaseDamage * (WV.DamageGrowth ^ (wave - 1)) * (boss and WV.BossDamageMultiplier or 1),
			WV.MaxDamage * (boss and WV.BossDamageMultiplier or 1))

		local npc = TungModels.buildNPC(variantName, {
			scale = boss and 2.1 or (0.9 + math.random() * 0.35),
			health = health,
			walkSpeed = WV.WalkSpeed + (boss and -2 or math.random() * 4),
			displayName = boss and ("SAHUR BOSS  •  wave " .. wave) or "Tung Tung Tung Sahur",
			boss = boss,
		})

		local angle = (index / math.max(count, 1)) * math.pi * 2 + math.random() * 0.4
		local radius = Config.World.ArenaRadius - 18
		local position = Vector3.new(math.sin(angle) * radius, 8, math.cos(angle) * radius)
		npc:PivotTo(CFrame.new(position) * CFrame.Angles(0, math.random() * math.pi * 2, 0))
		npc.Parent = folder

		local humanoid = npc:FindFirstChildOfClass("Humanoid") :: Humanoid
		local entry = {
			wave = wave,
			boss = boss,
			damage = damage,
			nextAttack = 0,
			nextRepath = 0,
			sway = npc:FindFirstChild("Torso") and npc.Torso:FindFirstChild("TungSway"),
			phase = math.random() * math.pi * 2,
			spawnedAt = os.clock(),
			dead = false,
		}
		active[npc] = entry
		aliveCount += 1

		humanoid.Died:Connect(function()
			onRaiderDied(npc, entry)
		end)

		-- boss aura
		if boss then
			local _, root = Util.getRig(npc)
			if root then
				local light = Instance.new("PointLight")
				light.Color = Color3.fromRGB(255, 90, 60)
				light.Range = 40
				light.Brightness = 3
				light.Parent = root
			end
		end
	end

	-- ─────────────────────────────────────────────────────────────────────────────

	local function tick(dt: number)
		local now = os.clock()
		for npc, entry in pairs(active) do
			if not npc.Parent or entry.dead then
				continue
			end
			local humanoid, root = Util.getRig(npc)
			if not humanoid or not root or humanoid.Health <= 0 then
				continue
			end

			-- waddle
			if entry.sway and entry.sway:IsA("Motor6D") then
				entry.phase += dt * (6 + humanoid.WalkSpeed * 0.25)
				local lean = math.sin(entry.phase) * 0.18
				local bob = math.abs(math.cos(entry.phase)) * 0.22
				entry.sway.C0 = CFrame.new(0, 0.7 + bob, 0) * CFrame.Angles(0, 0, lean)
			end

			if now >= entry.nextRepath then
				entry.nextRepath = now + 0.6
				local _, targetChar = nearestPlayer(root.Position, 500)
				if targetChar then
					entry.target = targetChar
					humanoid:MoveTo(targetChar:GetPivot().Position)
				else
					entry.target = nil
					humanoid:MoveTo(Vector3.new(math.random(-60, 60), 0, math.random(-60, 60)))
				end
				-- unstick
				if entry.lastPosition and (root.Position - entry.lastPosition).Magnitude < 1.5 then
					humanoid.Jump = true
				end
				entry.lastPosition = root.Position
			end

			local target = entry.target
			if target and target.Parent then
				local targetRoot = target:FindFirstChild("HumanoidRootPart")
				if targetRoot then
					local distance = (targetRoot.Position - root.Position).Magnitude
					if distance <= 8 and now >= entry.nextAttack then
						entry.nextAttack = now + 1.15
						CombatService.npcAttack(npc, target, entry.damage)
						Fx.impact(root, 0.85)

						local victim = Players:GetPlayerFromCharacter(target)
						if victim then
							local stolen = Economy.steal(victim, WV.StealPerHit)
							if stolen > 0 then
								Fx.floatingText(targetRoot.Position + Vector3.new(0, 4, 0),
									"-" .. Util.abbreviate(stolen), Color3.fromRGB(255, 110, 110), workspace)
							end
						end
					end
				end
			end

			-- despawn stragglers so a wave can't hang forever
			if now - entry.spawnedAt > 420 then
				humanoid.Health = 0
			end
		end
	end

	-- ─────────────────────────────────────────────────────────────────────────────

	function NPCService.startWave()
		if #Players:GetPlayers() == 0 then
			return
		end
		waveNumber += 1
		local count = math.min(WV.BaseCount + (waveNumber - 1) * WV.CountPerWave, WV.MaxCount)
		local boss = (waveNumber % WV.BossEvery == 0)

		broadcast({ phase = "warning", wave = waveNumber, seconds = WV.WarningTime, boss = boss })
		notifyRemote:FireAllClients({
			kind = "wave",
			title = ("SAHUR RAID %d INCOMING"):format(waveNumber),
			body = boss and "A BOSS is coming. tung tung tung." or ("%d raiders in %d seconds."):format(count, WV.WarningTime),
		})

		task.wait(WV.WarningTime)

		for i = 1, count do
			spawnRaider(waveNumber, i, count, false)
			task.wait(0.12)
		end
		if boss then
			spawnRaider(waveNumber, 0, count, true)
		end

		broadcast({ phase = "active", wave = waveNumber, remaining = aliveCount })
	end

	function NPCService.clearAll()
		for npc in pairs(active) do
			npc:Destroy()
		end
		active = {}
		aliveCount = 0
	end

	function NPCService.start()
		folder = Instance.new("Folder")
		folder.Name = "SahurRaiders"
		folder.Parent = workspace

		game:GetService("RunService").Heartbeat:Connect(function(dt)
			local ok, err = pcall(tick, dt)
			if not ok then
				warn("[Tung] NPC tick error: " .. tostring(err))
			end
		end)

		if not WV.Enabled then
			return
		end

		task.spawn(function()
			task.wait(WV.FirstWaveDelay)
			while true do
				local ok, err = pcall(NPCService.startWave)
				if not ok then
					warn("[Tung] wave error: " .. tostring(err))
				end
				task.wait(WV.Interval)
			end
		end)
	end

	function NPCService.currentWave(): number
		return waveNumber
	end

	return NPCService
end


__MODULES["PlotService"] = function()
	--[[
		PlotService.lua — owns the Tycoon instances and who is standing on what.
	]]

	local Req = __Req
	local Config = Req("Config")
	local Net = Req("Net")
	local Tycoon = Req("Tycoon")
	local Economy = Req("Economy")

	local Players = game:GetService("Players")

	local PlotService = {}

	local plots: { any } = {}
	local byOwner: { [Player]: any } = {}
	local reserved: { [number]: { userId: number, until_: number } } = {}

	local plotAssigned = Net.event("PlotAssigned")

	function PlotService.build(parent: Instance)
		local folder = parent:FindFirstChild("Plots") or parent
		for index = 1, Config.World.PlotCount do
			local tycoon = Tycoon.new(index, folder)
			plots[index] = tycoon
			PlotService.hookClaimPad(tycoon)
		end
	end

	function PlotService.hookClaimPad(tycoon)
		local lastTouch = 0
		local function onTouch(hit)
			-- cheapest possible early-out: an owned plot ignores touches entirely
			if tycoon.owner then
				return
			end
			if os.clock() - lastTouch < 0.5 then
				return
			end
			lastTouch = os.clock()
			local player = tycoon:playerFromHit(hit)
			if player and not byOwner[player] then
				PlotService.claim(player, tycoon.index)
			end
		end

		-- The marked pad is the affordance, but the ENTIRE plot floor claims an
		-- unclaimed plot. Hunting for a specific tile to stand on is a bad first
		-- thirty seconds, and there is no downside: the plot is free either way.
		for _, part in ipairs({ tycoon.claimPad, tycoon.padPart }) do
			if part then
				part.Touched:Connect(onTouch)
			end
		end
	end

	--- Puts a player on their own plot. Used on claim and on every respawn, so
	--- dying never costs you a walk back across the map.
	function PlotService.teleportToPlot(player: Player): boolean
		local tycoon = byOwner[player]
		local character = player.Character
		if not tycoon or not character or not character.PrimaryPart then
			return false
		end
		character:PivotTo(tycoon:ownerSpawnCFrame())
		return true
	end

	function PlotService.plotOf(player: Player)
		return byOwner[player]
	end

	local function isReservedForSomeoneElse(index: number, player: Player): boolean
		local hold = reserved[index]
		if not hold then
			return false
		end
		if os.clock() > hold.until_ then
			reserved[index] = nil
			return false
		end
		return hold.userId ~= player.UserId
	end

	function PlotService.claim(player: Player, index: number): boolean
		if byOwner[player] then
			return false
		end
		local tycoon = plots[index]
		if not tycoon or tycoon.owner then
			return false
		end
		if isReservedForSomeoneElse(index, player) then
			Economy.notify(player, {
				kind = "warn",
				title = "Plot reserved",
				body = "That factory is being held for a player who just disconnected.",
			})
			return false
		end

		reserved[index] = nil
		if not tycoon:assign(player) then
			return false
		end
		byOwner[player] = tycoon

		plotAssigned:FireClient(player, index)
		Economy.notify(player, {
			kind = "claim",
			title = "PLOT " .. index .. " CLAIMED",
			body = "Buy the first dropper to start the tung.",
		})
		Economy.push(player)

		PlotService.teleportToPlot(player)
		return true
	end

	function PlotService.release(player: Player, hold: boolean?)
		local tycoon = byOwner[player]
		if not tycoon then
			return
		end
		byOwner[player] = nil
		if hold then
			reserved[tycoon.index] = {
				userId = player.UserId,
				until_ = os.clock() + Config.Economy.OfflineGraceSeconds,
			}
		end
		tycoon:release()
	end

	--- Auto-place a player on the first free plot (used on join for convenience).
	function PlotService.autoAssign(player: Player): boolean
		-- honour a reservation from a recent disconnect first
		for index, hold in pairs(reserved) do
			if hold.userId == player.UserId and os.clock() <= hold.until_ then
				if PlotService.claim(player, index) then
					return true
				end
			end
		end
		for index = 1, Config.World.PlotCount do
			local tycoon = plots[index]
			if tycoon and not tycoon.owner and not isReservedForSomeoneElse(index, player) then
				return PlotService.claim(player, index)
			end
		end
		Economy.notify(player, {
			kind = "warn",
			title = "All plots taken",
			body = "Hang out in the arena — a plot frees up when someone leaves.",
		})
		return false
	end

	function PlotService.rebirth(player: Player)
		local tycoon = byOwner[player]
		if not tycoon then
			return
		end
		tycoon:rebirth(player)
	end

	function PlotService.start()
		Net.event("RequestRebirth").OnServerEvent:Connect(function(player)
			PlotService.rebirth(player)
		end)

		Net.event("RequestReset").OnServerEvent:Connect(function(player)
			PlotService.release(player, false)
			Economy.notify(player, { kind = "info", title = "Plot released", body = "Your progress is saved. Claim any plot to resume." })
		end)

		Players.PlayerRemoving:Connect(function(player)
			PlotService.release(player, true)
		end)

		-- keep the signage honest
		task.spawn(function()
			while true do
				task.wait(3)
				for _, tycoon in ipairs(plots) do
					local ok, err = pcall(function()
						tycoon:updateSign()
						if tycoon.owner then
							tycoon:refreshButtons()
						end
					end)
					if not ok then
						warn("[Tung] plot refresh error: " .. tostring(err))
					end
				end
			end
		end)
	end

	return PlotService
end


__MODULES["Tycoon"] = function()
	--[[
		Tycoon.lua — the standardized tycoon.

		One instance per plot. Everything it builds comes from Config.Buttons, so
		adding content is a data edit, never a code edit. The contract for a new
		entry is just:

			kind = "Dropper"   -> needs slot, variant, dropValue, dropRate
			kind = "Upgrader"  -> needs slot, variant, multiplier
			kind = "Belt"      -> needs speedBonus
			kind = "Structure" -> needs structure ("walls" | "roof")
			kind = "Gear"      -> needs grants (a Config.Bats id)

		Add a case to INSTALLERS below to invent a new kind.
	]]

	local Req = __Req
	local Config = Req("Config")
	local Util = Req("Util")
	local Fx = Req("Fx")
	local TungModels = Req("TungModels")
	local Economy = Req("Economy")
	local DataService = Req("DataService")
	local CombatService = Req("CombatService")
	local MapBuilder = Req("MapBuilder")

	local L = Config.Layout
	local W = Config.World

	local Tycoon = {}
	Tycoon.__index = Tycoon

	-- Buttons that aren't attached to a belt machine sit in a row on the open
	-- floor, spaced further apart than a button is wide. Positions live in Config
	-- so they scale with the plot instead of drifting into the wall when it grows.
	local MISC_SPOTS = L.MiscButtons

	local COLORS = {
		frame     = Color3.fromRGB(118, 122, 130),
		metal     = Color3.fromRGB(160, 164, 172),
		belt      = Color3.fromRGB(62, 62, 68),
		beltLine  = Color3.fromRGB(255, 176, 60),
		buttonOn  = Color3.fromRGB(110, 235, 150),
		buttonOff = Color3.fromRGB(230, 90, 90),
		vault     = Color3.fromRGB(146, 110, 72),
		gold      = Color3.fromRGB(255, 205, 90),
	}

	-- ─────────────────────────────────────────────────────────────────────────────
	-- construction helpers
	-- ─────────────────────────────────────────────────────────────────────────────

	local function newPart(parent, name, size, cf, color, material, collide)
		local p = Instance.new("Part")
		p.Name = name
		p.Size = size
		p.CFrame = cf
		p.Color = color
		p.Material = material or Enum.Material.SmoothPlastic
		p.Anchored = true
		p.CanCollide = collide ~= false
		p.TopSurface = Enum.SurfaceType.Smooth
		p.BottomSurface = Enum.SurfaceType.Smooth
		p.Parent = parent
		return p
	end

	-- ─────────────────────────────────────────────────────────────────────────────

	function Tycoon.new(index: number, parent: Instance)
		local self = setmetatable({}, Tycoon)

		self.index = index
		self.owner = nil :: Player?
		self.owned = {}
		self.objects = {}
		self.generation = 0
		self.beltSpeed = L.BeltSpeed
		self.dropCount = 0

		local model, cf = MapBuilder.buildPlotPad(parent, index)
		self.model = model
		self.cf = cf
		self.padPart = model:FindFirstChild("Pad")

		self.machines = Instance.new("Folder")
		self.machines.Name = "Machines"
		self.machines.Parent = model

		self.buttonsFolder = Instance.new("Folder")
		self.buttonsFolder.Name = "Buttons"
		self.buttonsFolder.Parent = model

		self.drops = Instance.new("Folder")
		self.drops.Name = "Drops"
		self.drops.Parent = model

		self:buildBelt()
		self:buildCollector()
		self:buildRebirthPad()
		self:buildClaimPad()

		-- An unclaimed plot shows a bare pad and a claim marker, nothing else.
		-- Leaving the vault and belt standing on an empty plot is what makes it
		-- look like there's a big block parked in front of the thing you're
		-- meant to walk onto.
		self:setFactoryVisible(false)
		self:updateSign()

		return self
	end

	--- Buy buttons are built on first claim, not at server start: every plot x 21
	--- buttons is a lot of instances to create just to immediately hide them.
	function Tycoon:ensureButtons()
		if self.buttonsBuilt then
			return
		end
		self.buttonsBuilt = true
		self:buildButtons()
	end

