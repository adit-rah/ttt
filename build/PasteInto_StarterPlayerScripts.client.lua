local __MODULES = {}
local __CACHE = {}
local __LOADING = {}

local function __Req(name)
	local cached = __CACHE[name]
	if cached ~= nil then
		return cached
	end
	if __LOADING[name] then
		error("[Tung] circular dependency while loading " .. tostring(name), 2)
	end
	local factory = __MODULES[name]
	if not factory then
		error("[Tung] module not found in packed build: " .. tostring(name), 2)
	end
	__LOADING[name] = true
	local value = factory()
	__LOADING[name] = nil
	__CACHE[name] = value
	return value
end


